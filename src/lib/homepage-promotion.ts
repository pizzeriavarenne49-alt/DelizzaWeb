import type { Product } from "@/types";
import { getPizzaDuoCoverRecipes, isDelizzaPizzaCategory, PIZZA_DUO_CATALOG_ID } from "@/lib/pizza-duo";

export type HomepagePromotionAction = "menu" | "product" | "counter";

export type PublishedPromotionInput = {
  title?: unknown;
  description?: unknown;
  buttonLabel?: unknown;
  action?: unknown;
  productId?: unknown;
  imagePath?: unknown;
  useDuoCover?: unknown;
  startsAt?: unknown;
  endsAt?: unknown;
};

export type HomepagePromotion = {
  title: string;
  description: string;
  buttonLabel: string;
  action: HomepagePromotionAction;
  productId: string | null;
  visual: { kind: "photo"; imageVersion: string } | { kind: "duo"; recipes: [Product, Product] };
  isDuo: boolean;
  priceCents: number | null;
  counterOnly: boolean;
  endsAt: string | null;
};

function string(value: unknown): string | null {
  return typeof value === "string" && value.trim() ? value.trim() : null;
}

function date(value: unknown): Date | null {
  if (value && typeof value === "object" && "toDate" in value && typeof (value as { toDate?: unknown }).toDate === "function") {
    return (value as { toDate: () => Date }).toDate();
  }
  return value instanceof Date ? value : null;
}

export function isCurrentHomepagePromotion(record: PublishedPromotionInput, now = new Date()): boolean {
  const startsAt = date(record.startsAt);
  const endsAt = date(record.endsAt);
  return (!startsAt || startsAt <= now) && (!endsAt || endsAt > now);
}

/** Storage paths are generated by the admin and cannot be chosen as URLs. */
export function isSafeHomepagePromotionImage(path: string | null): path is string {
  return path !== null && /^website\/d_lizza\/home-promo\/[a-f0-9]{32}\.jpg$/.test(path);
}

export function sortHomepageFeaturedProducts(products: Product[]): Product[] {
  return products
    .filter((product) => product.homepageFeatured === true && isDelizzaPizzaCategory(product.category) && product.kind !== "pizza_duo" && product.active && product.pizzaUnits === 1 && product.manualOutOfStock !== true && !(product.stockManaged === true && (!Number.isSafeInteger(product.stockQty) || (product.stockQty ?? 0) <= 0)))
    .sort((left, right) => (left.homepageOrder ?? 0) - (right.homepageOrder ?? 0) || left.id.localeCompare(right.id));
}

export function normalizePublishedHomepagePromotion(
  record: PublishedPromotionInput | null | undefined,
  products: Product[],
  privateDuoPriceCents: number | null,
  duoAvailableAtCounter: boolean,
  now = new Date(),
): HomepagePromotion | null {
  if (!record || !isCurrentHomepagePromotion(record, now)) return null;
  const title = string(record.title);
  const description = string(record.description);
  const buttonLabel = string(record.buttonLabel);
  const imagePath = string(record.imagePath);
  const action = record.action;
  if (!title || !description || !buttonLabel ||
    (action !== "menu" && action !== "product" && action !== "counter")) return null;
  if (record.useDuoCover != null && typeof record.useDuoCover !== "boolean") return null;

  const productId = typeof record.productId === "string" ? record.productId : null;
  const selected = productId ? products.find((product) => product.id === productId) : undefined;
  // A selected regular product must still be public and sellable. The private
  // canonical Duo is allowed only as a counter-only promotion while web sales
  // are closed.
  const isDuo = productId === PIZZA_DUO_CATALOG_ID;
  if (action === "product" && !selected && !isDuo) return null;
  const webDuo = Boolean(isDuo && selected);
  if (isDuo && !webDuo && !duoAvailableAtCounter) return null;
  let visual: HomepagePromotion["visual"];
  if (record.useDuoCover === true) {
    if (!isDuo || action !== "product" || record.imagePath != null) return null;
    const recipes = getPizzaDuoCoverRecipes(products);
    if (!recipes) return null;
    visual = { kind: "duo", recipes };
  } else {
    if (!isSafeHomepagePromotionImage(imagePath)) return null;
    visual = { kind: "photo", imageVersion: imagePath };
  }
  return {
    title,
    description,
    buttonLabel: isDuo && !webDuo && action === "product" ? "Commander par téléphone" : buttonLabel,
    action: isDuo && !webDuo ? "counter" : action,
    productId: selected?.id ?? null,
    visual,
    isDuo,
    priceCents: selected?.price_cents ?? (isDuo ? privateDuoPriceCents : null),
    counterOnly: isDuo && !webDuo,
    endsAt: date(record.endsAt)?.toISOString() ?? null,
  };
}

/** Keep the browser timer within the signed 32-bit setTimeout range. */
export function homepagePromotionExpiryDelay(endMs: number, nowMs: number): number {
  return Math.max(0, Math.min(2_147_000_000, endMs - nowMs));
}
